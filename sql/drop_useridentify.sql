-- ============================================================
-- useridentify 테이블 제거
-- - userinfo의 데이터는 그대로 유지
-- - userinfo.user_id → useridentify.user_id FK 제거
-- - userinfo.user_id는 identity로 동작하도록 보장
-- - 연관 트리거/함수(insert_user_data)도 함께 제거
-- ============================================================

-- 1) userinfo.user_id가 identity가 아니면 identity로 전환
--    (fix_userinfo_user_id.sql이 이미 적용되어 있다면 no-op)
DO $$
BEGIN
  ALTER TABLE public.userinfo
    ALTER COLUMN user_id ADD GENERATED BY DEFAULT AS IDENTITY;
EXCEPTION
  WHEN duplicate_object THEN NULL;            -- 이미 identity
  WHEN invalid_table_definition THEN NULL;    -- 이미 default/identity 존재
  WHEN others THEN NULL;
END $$;

-- identity 시퀀스를 현재 최대 user_id+1로 맞춤 (중복 방지)
SELECT setval(
  pg_get_serial_sequence('public.userinfo', 'user_id'),
  COALESCE((SELECT MAX(user_id) FROM public.userinfo), 0) + 1,
  false
);

-- 2) userinfo → useridentify FK 제약 탐색 및 제거
DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN
    SELECT conname
    FROM pg_constraint c
    JOIN pg_class t ON c.conrelid = t.oid
    JOIN pg_class ref ON c.confrelid = ref.oid
    WHERE c.contype = 'f'
      AND t.relname = 'userinfo'
      AND ref.relname = 'useridentify'
  LOOP
    EXECUTE format('ALTER TABLE public.userinfo DROP CONSTRAINT %I', r.conname);
  END LOOP;
END $$;

-- 3) auth.users 위에 달려있을 수 있는 insert_user_data 트리거/함수 제거
--    (이 함수가 useridentify에 insert하므로 테이블 드롭 전에 제거 필요)
DROP FUNCTION IF EXISTS public.insert_user_data() CASCADE;

-- 4) useridentify 테이블 제거
DROP TABLE IF EXISTS public.useridentify CASCADE;
