create table public.collections (
  id integer generated by default as identity not null,
  title text not null,
  description text null,
  created_at date not null default CURRENT_DATE,
  user_id integer not null,
  tags jsonb null,
  user_name text not null,
  primary_keywords jsonb null,
  selection_num integer not null default 0,
  like_num integer null default 0,
  is_public boolean not null default false,
  category_id integer not null default 0,
  image_id uuid null,
  constraint collections_pkey primary key (id, user_id),
  constraint unique_collection_id unique (id),
  constraint collections_category_id_fkey foreign KEY (category_id) references categoryinfo (category_id) on update CASCADE on delete CASCADE,
  constraint collections_image_id_fkey foreign KEY (image_id) references images (image_id) on delete set null,
  constraint collections_user_id_fkey foreign KEY (user_id) references userinfo (user_id) on update CASCADE on delete CASCADE,
  constraint check_tags_format_no_whitespace check (validate_tags_format (tags))
) TABLESPACE pg_default;

create index IF not exists idx_tags_gin on public.collections using gin (tags jsonb_path_ops) TABLESPACE pg_default;

create index IF not exists idx_keywords_on_collections on public.collections using gin (primary_keywords jsonb_path_ops) TABLESPACE pg_default;