create table public.categoryinfo (
  category_id smallint generated by default as identity not null,
  category_name text not null,
  category_description text null,
  constraint categoryinfo_pkey primary key (category_id),
  constraint categoryinfo_id_key unique (category_id)
) TABLESPACE pg_default;

-- Row Level Security: server(service_role) 전용. anon/authenticated 전면 차단.
-- service_role은 GRANT/RLS를 모두 우회하므로 백엔드 접근은 유지된다.
alter table public.categoryinfo enable row level security;
revoke all on table public.categoryinfo from anon, authenticated;
