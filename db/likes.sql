create table public.likes (
  user_id integer not null,
  collection_id integer not null,
  id bigint generated by default as identity not null,
  liked_at timestamp with time zone null default now(),
  constraint likes_pkey primary key (user_id, collection_id),
  constraint unique_like unique (collection_id, user_id),
  constraint likes_collection_id_fkey foreign KEY (collection_id) references collections (id) on update CASCADE on delete CASCADE,
  constraint likes_user_id_fkey foreign KEY (user_id) references userinfo (user_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create trigger update_like_num_trigger
after INSERT
or DELETE on likes for EACH row
execute FUNCTION update_like_num ();

-- Row Level Security: server(service_role) 전용. anon/authenticated 전면 차단.
-- service_role은 GRANT/RLS를 모두 우회하므로 백엔드 접근은 유지된다.
alter table public.likes enable row level security;
revoke all on table public.likes from anon, authenticated;
