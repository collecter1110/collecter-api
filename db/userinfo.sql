create table public.userinfo (
  name text null,
  email text not null,
  description text null,
  user_id integer generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  deleted_at timestamp with time zone null,
  image_id uuid null,
  terms_agreed boolean not null default false,
  last_active_at timestamp with time zone null,
  push_enabled boolean not null default true,
  constraint userinfo_pkey primary key (user_id),
  constraint unique_userid_username unique (user_id, name),
  constraint userinfo_email_key unique (email),
  constraint userinfo_name_key unique (name),
  constraint userinfo_image_id_fkey foreign KEY (image_id) references images (image_id) on delete set null
) TABLESPACE pg_default;

create index IF not exists userinfo_deleted_at_idx on public.userinfo using btree (deleted_at) TABLESPACE pg_default;

create index IF not exists userinfo_name_gin_idx on public.userinfo using gin (to_tsvector('simple'::regconfig, name)) TABLESPACE pg_default;

create index IF not exists userinfo_last_active_at_idx on public.userinfo using btree (last_active_at) TABLESPACE pg_default;

-- Row Level Security: server(service_role) 전용. anon/authenticated 전면 차단.
-- service_role은 GRANT/RLS를 모두 우회하므로 백엔드 접근은 유지된다.
alter table public.userinfo enable row level security;
revoke all on table public.userinfo from anon, authenticated;
